-- Canonical logical schema only. Preserve receipts across JVMs and member rejoin.
-- Apply with writers stopped, backup verified, and the intended schema selected.
CREATE TABLE IF NOT EXISTS LOGIN_LIMITS (
 CLIENT_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 WINDOW_START_MS BIGINT NOT NULL,
 ATTEMPTS INT NOT NULL,
 CHECK (WINDOW_START_MS>=0 AND ATTEMPTS>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS LOGIN_ATTEMPTS (
 OPERATION_ID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 CLIENT_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 EMAIL_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 REQUEST_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 HTTP_STATUS SMALLINT NOT NULL,
 USER_ID INT NULL,
 USER_GENERATION CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 CREATED_AT_MS BIGINT NOT NULL,
 CHECK (HTTP_STATUS IN (200,401,429)),
 CHECK ((HTTP_STATUS=200 AND USER_ID IS NOT NULL AND USER_GENERATION IS NOT NULL)
     OR (HTTP_STATUS<>200 AND USER_ID IS NULL AND USER_GENERATION IS NULL))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS LOGIN_STATUS_LIMITS (
 CLIENT_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 WINDOW_START_MS BIGINT NOT NULL,
 ATTEMPTS INT NOT NULL,
 CHECK (WINDOW_START_MS>=0 AND ATTEMPTS>=0)
) ENGINE=InnoDB;
-- Runtime: LOGIN_ATTEMPTS SELECT,INSERT only; both budget tables SELECT,INSERT,
-- UPDATE,DELETE. No raw IP, email, password or credential hash is stored here.
-- Do not delete unacknowledged attempt receipts to free space or reset a budget.
