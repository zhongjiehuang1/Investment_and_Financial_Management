-- Run on BOTH nodes using a maintenance identity before enabling cluster mode.
CREATE TABLE IF NOT EXISTS CLUSTER_COORDINATOR (
 ID INT PRIMARY KEY, STORE_UUID CHAR(36) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CLUSTER_GATE (
 ID INT PRIMARY KEY, OPERATION_ID CHAR(36) NULL
) ENGINE=InnoDB;
INSERT IGNORE INTO CLUSTER_GATE(ID,OPERATION_ID) VALUES(1,NULL);
CREATE TABLE IF NOT EXISTS CLUSTER_OPERATIONS (
 ID CHAR(36) PRIMARY KEY, OWNER_KEY VARCHAR(128) NOT NULL,
 REQUEST_HASH CHAR(64) NOT NULL, STATE VARCHAR(16) NOT NULL,
 ENDPOINT VARCHAR(160) NULL,
 DELETE_RESULT_HASH CHAR(64) NULL,
 DELETE_RESULT_EXPIRES DATETIME(6) NULL,
 TRANSACTION_UID VARCHAR(128) NULL, CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CLUSTER_BRANCHES (
 OPERATION_ID CHAR(36) NOT NULL, NODE_ID INT NOT NULL, FORMAT_ID INT NOT NULL,
 GLOBAL_ID VARBINARY(64) NOT NULL, BRANCH_ID VARBINARY(64) NOT NULL,
 XID_KEY CHAR(64) NOT NULL, TERMINAL VARCHAR(16) NULL,
 PRIMARY KEY(OPERATION_ID,NODE_ID), UNIQUE KEY(XID_KEY,NODE_ID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CLUSTER_RESULTS (
 OPERATION_ID CHAR(36) PRIMARY KEY, PAYLOAD LONGTEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CLUSTER_RECEIPTS (
 XID_KEY CHAR(64) PRIMARY KEY, OPERATION_ID CHAR(36) NOT NULL
) ENGINE=InnoDB;
